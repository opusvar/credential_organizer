"""Tests for the resource catalog: parsing, checks, tiergate builder, reach table."""
from __future__ import annotations

import copy
import datetime as dt
from pathlib import Path

import pytest
import yaml

from cvc.access import BUILDERS, RegistryError, parse_registry
from cvc.access.catalog import build_tiergate, can_reach, reachable
from cvc.access.check import check_registry
from cvc.access.cli import main
from cvc.access.graph import build_graph
from cvc.tiergate.core import parse_config

ROOT = Path(__file__).resolve().parent.parent
EXAMPLE = ROOT / "access" / "registry.example.yaml"
TODAY = dt.date(2026, 10, 31)


def _data():
    return yaml.safe_load(EXAMPLE.read_text(encoding="utf-8"))


def _with(**resources):
    d = _data()
    d["resources"] = resources
    return d


def _errors(data):
    with pytest.raises(RegistryError) as ei:
        parse_registry(data)
    return ei.value.errors


def test_example_parses_with_derived_fields():
    reg = parse_registry(_data())
    assert reg.resources["books"].host == "books.example.home"     # from url
    assert reg.resources["portainer"].host == "portainer.example.home"  # port stripped
    assert reg.resources["ha"].ha_level == "limited-control"
    assert reg.resources["dashboard"].passkey_required
    assert not reg.resources["ha"].passkey_required
    assert reg.resources["portainer"].passkey_required


def test_resources_optional():
    d = _data()
    del d["resources"]
    assert parse_registry(d).resources == {}


@pytest.mark.parametrize("raw,needle", [
    ({"kind": "media", "min_tier": "low"}, "requires a host or url"),
    ({"host": "a.home", "kind": "toaster", "min_tier": "low"}, ".kind: must be one of"),
    ({"host": "a.home", "kind": "media"}, ".min_tier: required"),
    ({"url": "ftp://a.home", "kind": "media", "min_tier": "low"}, ".url: must be an http"),
    ({"host": "a.home:8080", "kind": "media", "min_tier": "low"}, "hostname only"),
    ({"host": "a.home", "kind": "media", "min_tier": "low", "ha_level": "view"},
     "only valid for kind ha"),
    ({"host": "a.home", "kind": "ha", "min_tier": "low", "ha_level": "none"}, ".ha_level"),
    ({"host": "a.home", "kind": "media", "min_tier": "low", "port": 1}, "unknown field"),
])
def test_structural_errors(raw, needle):
    assert any(needle in e for e in _errors(_with(x=raw)))


def test_check_unknown_tier_and_duplicate_host():
    reg = parse_registry(_with(
        a={"host": "Dup.home", "kind": "media", "min_tier": "superuser"},
        b={"url": "https://dup.home/x", "kind": "library", "min_tier": "low"}))
    msgs = [(f.level, f.path, f.message) for f in check_registry(reg, TODAY)
            if f.path.startswith("resources.")]
    assert ("error", "resources.a", msgs[0][2]) == msgs[0] and "unknown min_tier" in msgs[0][2]
    assert msgs[1][1] == "resources.b" and "duplicate host 'dup.home'" in msgs[1][2]
    with pytest.raises(RegistryError):
        build_tiergate(reg)


def test_example_check_has_no_resource_findings():
    reg = parse_registry(_data())
    assert not [f for f in check_registry(reg, TODAY) if f.path.startswith("resources")]


def test_tiergate_output_loads_in_tiergate():
    assert BUILDERS["tiergate"] is build_tiergate
    text = build_tiergate(parse_registry(_data()))
    assert text.startswith("# GENERATED by `cvc-access build tiergate`")
    cfg = parse_config(yaml.safe_load(text))
    assert cfg.default_min_tier is None
    d = "orangepi6.humpback-krait.ts.net"
    assert cfg.hosts == {f"books.{d}": "guest-long", f"dashboard.{d}": "high",
                         f"ha.{d}": "medium", f"media.{d}": "media-only",
                         f"portainer.{d}": "admin"}
    reg_cfg = parse_config(yaml.safe_load(
        build_tiergate(parse_registry(_data()), registry_hosts=True)))
    assert reg_cfg.hosts == {"books.example.home": "guest-long", "dash.example.home": "high",
                             "ha.example.home": "medium", "media.example.home": "media-only",
                             "portainer.example.home": "admin"}
    assert cfg.min_tier_for("unknown.home") is None


def test_can_reach_rules():
    reg = parse_registry(_data())
    r = reg.resources
    nathan, sam, visitor = (reg.people[p] for p in ("nathan", "sam", "visitor"))
    assert all(can_reach(nathan, x, TODAY) for x in r.values())
    assert [x.id for x in reachable(reg, sam, TODAY)] == ["books", "ha", "media"]
    assert can_reach(visitor, r["books"], TODAY)
    assert not can_reach(visitor, r["books"], dt.date(2027, 1, 1))  # expired


def test_graph_reach_table():
    out = build_graph(parse_registry(_data()), TODAY)
    assert "## What each person can reach" in out
    assert "| sam | medium | yes | - | yes | yes | - |" in out
    assert "| nathan | owner | yes | yes* | yes | yes | yes* |" in out
    later = build_graph(parse_registry(_data()), dt.date(2027, 1, 1))
    assert "| visitor | guest-long (expired) | - | - | - | - | - |" in later


def test_graph_without_resources_has_no_sections():
    d = copy.deepcopy(_data())
    del d["resources"]
    out = build_graph(parse_registry(d), TODAY)
    assert "## Resources" not in out and "can reach" not in out


def test_cli_build_tiergate(tmp_path, capsys):
    out = tmp_path / "tg.yaml"
    assert main(["build", "tiergate", "--registry", str(EXAMPLE), "--out", str(out)]) == 0
    assert "ha.orangepi6.humpback-krait.ts.net: medium" in out.read_text()
    bad = tmp_path / "bad.yaml"
    bad.write_text(yaml.safe_dump(_with(a={"host": "a.home", "kind": "media",
                                            "min_tier": "nope"}), sort_keys=False))
    assert main(["build", "tiergate", "--registry", str(bad)]) == 1
    assert "unknown min_tier" in capsys.readouterr().err
