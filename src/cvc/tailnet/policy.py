"""Build the owner tailnet's HuJSON ACL policy.

Owner devices (people listed as owners, resolved via the access registry) get full
access. Everything shared out to other tailnets (family, long-guests, short-guests,
agents, machines) arrives as `autogroup:shared` and may reach only the Traefik proxy
(443) and the cvc broker (8710) on the services node.
"""
from __future__ import annotations

import json

from cvc.access.model import Registry

SERVICE_HOST = "100.106.97.34"
PROXY_PORT = 443
BROKER_PORT = 8710
SHARED_TAILNETS = ("family", "long-guests", "short-guests", "agents", "machines")
FREE_PLAN_MAX_GROUPS = 3


class PolicyError(ValueError):
    pass


def _emails(registry: Registry, people: list[str]) -> list[str]:
    out = []
    for pid in people:
        person = registry.people.get(pid)
        if person is None:
            raise PolicyError(f"unknown person: {pid}")
        if not person.email:
            raise PolicyError(f"person {pid} has no email (needed as Tailscale login)")
        out.append(person.email)
    return out


def build_policy(registry: Registry, owners: list[str],
                 extra_groups: dict[str, list[str]] | None = None,
                 ) -> tuple[dict, list[str]]:
    """Return (policy dict, warnings). `owners`/group members are registry person ids."""
    if not owners:
        raise PolicyError("at least one owner is required")
    groups = {"group:owner": _emails(registry, owners)}
    for name, members in (extra_groups or {}).items():
        key = name if name.startswith("group:") else f"group:{name}"
        if key in groups:
            raise PolicyError(f"duplicate group: {key}")
        groups[key] = _emails(registry, members)
    warnings = []
    if len(groups) > FREE_PLAN_MAX_GROUPS:
        warnings.append(f"{len(groups)} groups exceeds the Tailscale free-plan limit of "
                        f"{FREE_PLAN_MAX_GROUPS}")
    shared_dst = [f"services-node:{PROXY_PORT}", f"services-node:{BROKER_PORT}"]
    policy = {
        "groups": groups,
        "hosts": {"services-node": SERVICE_HOST},
        "acls": [
            {"action": "accept", "src": ["group:owner"], "dst": ["*:*"]},
            {"action": "accept", "src": ["autogroup:shared"], "dst": shared_dst},
        ],
        "tests": [
            {"src": "autogroup:shared", "accept": shared_dst,
             "deny": ["services-node:22", "services-node:8443"]},
        ],
    }
    return policy, warnings


def render_hujson(policy: dict) -> str:
    header = [
        "// Owner-tailnet ACL policy - generated by `python -m cvc.tailnet policy`.",
        "// Do not edit by hand; apply manually in the Tailscale admin console.",
        "// Shared-in tailnets (" + ", ".join(SHARED_TAILNETS) + ") appear as",
        (f"// autogroup:shared and may reach only {SERVICE_HOST}:{PROXY_PORT} (Traefik) "
         f"and :{BROKER_PORT} (broker)."),
    ]
    return "\n".join(header) + "\n" + json.dumps(policy, indent=2) + "\n"
